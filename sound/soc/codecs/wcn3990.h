#ifndef __WCN3990_H__
#define __WCN3990_H__

#define SLIM_MANF_ID_QCOM	0x217
#define SLIM_PROD_CODE_WCN3990	0x220
#define SLIM_REG_OFFSET_WCN3990	0x0800

#define WCN3990_HW_REV_MSB			(SLIM_REG_OFFSET_WCN3990 + 0x00000001)
#define WCN3990_HW_REV_LSB			(SLIM_REG_OFFSET_WCN3990 + 0x00000002)
#define WCN3990_RX_PORT_CFGN(n)			(SLIM_REG_OFFSET_WCN3990 + 0x00000040 + (n - 0x10))
#define WCN3990_TX_PORT_CFGN(n)			(SLIM_REG_OFFSET_WCN3990 + 0x00000050 + n)
#define WCN3990_TX_PORTn_MULTI_CHNL_0(n)	(SLIM_REG_OFFSET_WCN3990 + 0x00000100 + 0x4*n)
#define WCN3990_RX_PORTn_MULTI_CHNL_0(n)	(SLIM_REG_OFFSET_WCN3990 + 0x00000180 + 0x4*(n - 16))
#define WCN3990_TX_PORT_RECOVERY		(SLIM_REG_OFFSET_WCN3990 + 0x000001F0 + n)

/* Port mapping */
#define WCN3990_BT_SLIM_TX_PORT		0
#define WCN3990_FM_SLIM_TX1_PORT	1
#define WCN3990_FM_SLIM_TX2_PORT	2
#define WCN3990_BT_SLIM_RX_PORT		16
#define WCN3990_BT_SLIM_SPLIT_RX_PORT	17

/* Register bits */
#define WCN3990_ENABLE_OVERRUN_RECOVERY		(0x1 << 1)
#define WCN3990_ENABLE_UNDERRUN_RECOVERY	(0x1 << 0);
#define WCN3990_PORT_ENABLE			(0x1 << 0)
#define WCN3990_PORT_DISABLE			(0x0 << 0)
#define WCN3990_PORT_WM_L1			(0x1 << 1)
#define WCN3990_PORT_WM_L8			(0x8 << 1)
#define WCN3990_PORT_WM_LB			(0xB << 1)

enum {
	WCN3990_FM_SLIM_TX = 0,
	WCN3990_BT_SLIM_TX,
	WCN3990_BT_SLIM_RX,
	WCN3990_BT_SPLIT_SLIM_RX,
	WCN3990_NUM_OF_DAIS,
};

enum {
	WCN3990_PORT_TYPE_TX = 0,
	WCN3990_PORT_TYPE_RX = 1,
	WCN3990_PORT_TYPE_FM = 2,
};

#endif /* __WCN3990_H__ */
